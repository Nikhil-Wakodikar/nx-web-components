export function getIconNode(name: string): IconNode | undefined {
  const normalized = name
    .trim()
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .toLowerCase()
    .replace(/-(outline|sharp)$/, '')
    .replace(/[^a-z0-9]/g, '');

  return iconNodes[normalized];
}
